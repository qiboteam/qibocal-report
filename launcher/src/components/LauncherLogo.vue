<!--
  The Qibocamp logo, inlined so it takes the colour of the text around it.

  Two forms of the same drawing, both generated by `scripts/logo.py`: the
  wordmark — the Qibo Q read as a dial, followed by QIBOCAL — for the page
  corner, and the mark alone, the Q, wherever only a square fits.
-->
<template>
  <span class="lx-logo-svg" :class="mark ? 'is-mark' : 'is-wordmark'" :style="{ height: `${height}px` }" v-html="svg" />
</template>

<script setup>
import { computed } from 'vue'
import wordmark from '../assets/qibocamp-logo.svg?raw'
import markSvg from '../assets/qibocamp-mark.svg?raw'

const props = defineProps({
  /** The Q alone, instead of the whole word. */
  mark: { type: Boolean, default: false },
  height: { type: [Number, String], default: 26 }
})

const svg = computed(() => (props.mark ? markSvg : wordmark))
</script>
